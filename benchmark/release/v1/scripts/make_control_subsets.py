#!/usr/bin/env python3
"""Describe the purposive control subsets and their selection timing.

Reads only tracked release files: the final Codex run CSV, the follow-up
canonical manifest, and task_details.tex. Writes a per-task table and a JSON
summary comparing each control subset with its complement on the primary
no-skill/with-skill estimand (task-balanced, models averaged within task).

Selection timing is established from git history: each task list appears in
benchmark/matrix.py in a commit authored before the first run of the
corresponding control condition. Run identifiers are UTC, so the comparison is
made in UTC and the script fails if it does not hold.
"""

from __future__ import annotations

import csv
import json
import os
import statistics
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

PAPER_DIR = Path(
    os.environ.get("M4BENCH_PAPER_DIR", Path(__file__).resolve().parents[1])
).resolve()
PLANNING = PAPER_DIR / "planning"
TABLES = PAPER_DIR / "tables"
# Commits in which each task list first appears, unchanged since, in
# benchmark/matrix.py, with author dates in UTC (verifiable with
# `git show -s --format=%aI <commit>`; committer dates reflect a later rewrite).
SELECTION_COMMITS = {
    "decoy_rawsql": ("159b0a18", "2026-05-02T14:44:09+00:00"),
    # The operational-spec control reuses the eight-task sentinel list. The commit
    # that added the condition itself (8492345e, 2026-05-06T03:46:26+00:00) was
    # authored after the first operational-spec run, so it is not the record.
    "operational_spec": ("9cb1c81e", "2026-04-23T23:16:24+00:00"),
}


def task_details() -> dict[str, dict[str, str]]:
    details = {}
    for line in (TABLES / "task_details.tex").read_text().splitlines():
        fields = [part.strip().removesuffix(r"\\").strip() for part in line.split("&")]
        if len(fields) == 6 and fields[5].isdigit():
            details[fields[0]] = {"mode": fields[1], "database": fields[2]}
    return details


def family(task: str) -> str:
    name = task.removeprefix("mimic-").removeprefix("eicu-").removesuffix("-raw")
    for suffix in ("-24h", "-48h"):
        name = name.removesuffix(suffix)
    return name


def run_timestamp(run_id: str) -> str:
    date, time = run_id.rsplit("_", 2)[-2:]
    return f"{date}_{time}"


def main() -> None:
    rows = list(csv.DictReader((PLANNING / "final_codex_runs.csv").open()))
    rewards: dict[tuple, list[float]] = defaultdict(list)
    subsets: dict[str, set[str]] = defaultdict(set)
    first_run: dict[str, str] = {}
    for row in rows:
        if row["schema"] != "native":
            continue
        rewards[(row["task"], row["model"], row["condition"])].append(
            float(row["reward"])
        )
        subsets[row["condition"]].add(row["task"])
        stamp = run_timestamp(row["run_id"])
        first_run[row["condition"]] = min(first_run.get(row["condition"], stamp), stamp)
    followup = json.loads((PLANNING / "followup_canonical_manifest.json").read_text())
    spec_runs = [
        r
        for r in followup["canonical_runs"]
        if r["run_key"]["condition"] == "operational-spec"
    ]
    spec_tasks = {r["run_key"]["task"] for r in spec_runs}
    spec_first = min(r["timestamp_key"] for r in spec_runs)
    decoy = subsets["with-skill-decoy"]
    if decoy != subsets["with-skill-rawsql"]:
        raise SystemExit("Decoy and raw-SQL subsets differ; describe them separately")

    models = sorted({row["model"] for row in rows})
    details = task_details()
    deltas = {}
    for task in sorted(subsets["no-skill"]):
        per_model = [
            statistics.mean(rewards[(task, m, "with-skill")])
            - statistics.mean(rewards[(task, m, "no-skill")])
            for m in models
        ]
        deltas[task] = statistics.mean(per_model)

    def describe(name: str, members: set[str]) -> dict:
        complement = set(deltas) - members
        return {
            "tasks": sorted(members),
            "families": len({family(t) for t in members}),
            "standard": sum(details[t]["mode"] == "standard" for t in members),
            "raw": sum(details[t]["mode"] == "raw" for t in members),
            "mimic": sum(details[t]["database"] == "MIMIC-IV" for t in members),
            "eicu": sum(details[t]["database"] == "eICU" for t in members),
            "targeted_delta": statistics.mean(deltas[t] for t in members),
            "complement_tasks": len(complement),
            "complement_targeted_delta": statistics.mean(deltas[t] for t in complement),
            "selection_commit": SELECTION_COMMITS[name][0],
            "selection_committed_at": SELECTION_COMMITS[name][1],
        }

    summary = {
        "description": "Generated by make_control_subsets.py from tracked release files.",
        "all_tasks_targeted_delta": statistics.mean(deltas.values()),
        "total_families": len({family(t) for t in deltas}),
        "decoy_rawsql": {
            **describe("decoy_rawsql", decoy),
            "first_run": min(
                first_run["with-skill-decoy"], first_run["with-skill-rawsql"]
            ),
        },
        "operational_spec": {
            **describe("operational_spec", spec_tasks),
            "first_run": spec_first,
        },
    }
    for name in ("decoy_rawsql", "operational_spec"):
        committed = datetime.fromisoformat(summary[name]["selection_committed_at"])
        first = datetime.strptime(summary[name]["first_run"], "%Y%m%d_%H%M%S")
        if committed >= first.replace(tzinfo=timezone.utc):
            raise SystemExit(f"{name}: selection commit does not precede first run")
    lines = [
        r"\begin{tabular}{llllrcc}",
        r"\toprule",
        r"Task & Family & Mode & Database & Targeted delta & Decoy/raw SQL & Operational spec \\",
        r"\midrule",
    ]
    for task in sorted(deltas, key=lambda t: deltas[t], reverse=True):
        lines.append(
            f"{task} & {family(task)} & {details[task]['mode']} & {details[task]['database']} & "
            f"{deltas[task]:.3f} & {'yes' if task in decoy else ''} & {'yes' if task in spec_tasks else ''} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    (TABLES / "codex_control_subsets.tex").write_text("\n".join(lines))
    (PLANNING / "control_subsets_summary.json").write_text(
        json.dumps(summary, indent=2) + "\n"
    )
    print(
        json.dumps({k: v for k, v in summary.items() if k != "description"}, indent=2)
    )


if __name__ == "__main__":
    main()
